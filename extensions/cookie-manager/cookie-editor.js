const CookieEditor = {
  parseCookieString(str) {
    const cookies = [];
    const lines = str.split('\n').filter((l) => l.trim() && !l.startsWith('#'));
    for (const line of lines) {
      const parts = line.split('\t');
      if (parts.length >= 7) {
        cookies.push({
          domain: parts[0],
          secure: parts[1].toUpperCase() === 'TRUE',
          path: parts[2] || '/',
          expires: parseInt(parts[3], 10) || -1,
          name: parts[4],
          value: parts[5],
          httpOnly: parts[6] ? parts[6].toUpperCase() === 'TRUE' : false
        });
      }
    }
    return cookies;
  },

  toNetscapeFormat(cookies) {
    let output = '# Netscape HTTP Cookie File\n';
    output += '# https://curl.se/rfc/cookie_spec.html\n';
    output += '# This file was generated by Cookie Manager\n\n';
    for (const cookie of cookies) {
      const domain = cookie.domain.startsWith('.') ? cookie.domain : `.${cookie.domain}`;
      const secure = cookie.secure ? 'TRUE' : 'FALSE';
      const expiry = cookie.expirationDate || Math.floor(Date.now() / 1000) + 86400;
      const httpOnly = cookie.httpOnly ? 'TRUE' : 'FALSE';
      output += `${domain}\t${secure}\t${cookie.path || '/'}\t${expiry}\t${cookie.name}\t${cookie.value}\t${httpOnly}\n`;
    }
    return output;
  },

  toJSON(cookies) {
    return JSON.stringify(cookies, null, 2);
  },

  parseJSON(str) {
    try {
      const parsed = JSON.parse(str);
      return Array.isArray(parsed) ? parsed : [parsed];
    } catch (e) {
      throw new Error('Invalid JSON format');
    }
  },

  validateCookie(cookie) {
    const errors = [];
    if (!cookie.name || cookie.name.trim() === '') {
      errors.push('Cookie name is required');
    }
    if (!cookie.domain || cookie.domain.trim() === '') {
      errors.push('Cookie domain is required');
    }
    if (cookie.name && /[\s;=]/.test(cookie.name)) {
      errors.push('Cookie name contains invalid characters');
    }
    if (cookie.expirationDate && cookie.expirationDate < Math.floor(Date.now() / 1000)) {
      errors.push('Expiration date is in the past');
    }
    return { valid: errors.length === 0, errors };
  },

  formatCookieForDisplay(cookie) {
    const expiry = cookie.expirationDate
      ? new Date(cookie.expirationDate * 1000).toLocaleString()
      : 'Session';
    const size = new TextEncoder().encode(`${cookie.name}=${cookie.value}`).length;
    return {
      ...cookie,
      expiryFormatted: expiry,
      size,
      isSession: !cookie.expirationDate,
      domainClean: cookie.domain.startsWith('.') ? cookie.domain.slice(1) : cookie.domain
    };
  },

  sortCookies(cookies, sortBy = 'name', ascending = true) {
    return [...cookies].sort((a, b) => {
      let valA, valB;
      switch (sortBy) {
        case 'name':
          valA = a.name.toLowerCase();
          valB = b.name.toLowerCase();
          break;
        case 'domain':
          valA = a.domain.toLowerCase();
          valB = b.domain.toLowerCase();
          break;
        case 'expires':
          valA = a.expirationDate || 0;
          valB = b.expirationDate || 0;
          break;
        case 'size':
          valA = new TextEncoder().encode(`${a.name}=${a.value}`).length;
          valB = new TextEncoder().encode(`${b.name}=${b.value}`).length;
          break;
        default:
          valA = a.name.toLowerCase();
          valB = b.name.toLowerCase();
      }
      if (valA < valB) return ascending ? -1 : 1;
      if (valA > valB) return ascending ? 1 : -1;
      return 0;
    });
  },

  filterCookies(cookies, query) {
    if (!query) return cookies;
    const q = query.toLowerCase();
    return cookies.filter(
      (c) =>
        c.name.toLowerCase().includes(q) ||
        c.value.toLowerCase().includes(q) ||
        c.domain.toLowerCase().includes(q) ||
        (c.path && c.path.toLowerCase().includes(q))
    );
  },

  groupByDomain(cookies) {
    const groups = {};
    for (const cookie of cookies) {
      const domain = cookie.domain;
      if (!groups[domain]) groups[domain] = [];
      groups[domain].push(cookie);
    }
    return groups;
  },

  getStats(cookies) {
    const total = cookies.length;
    const session = cookies.filter((c) => !c.expirationDate).length;
    const persistent = total - session;
    const secure = cookies.filter((c) => c.secure).length;
    const httpOnly = cookies.filter((c) => c.httpOnly).length;
    const totalSize = cookies.reduce(
      (sum, c) => sum + new TextEncoder().encode(`${c.name}=${c.value}`).length,
      0
    );
    const domains = [...new Set(cookies.map((c) => c.domain))];
    const sizeByDomain = {};
    for (const cookie of cookies) {
      const size = new TextEncoder().encode(`${cookie.name}=${cookie.value}`).length;
      sizeByDomain[cookie.domain] = (sizeByDomain[cookie.domain] || 0) + size;
    }
    return {
      total,
      session,
      persistent,
      secure,
      httpOnly,
      totalSize,
      domains: domains.length,
      sizeByDomain,
      avgSizePerCookie: total > 0 ? Math.round(totalSize / total) : 0
    };
  }
};

if (typeof module !== 'undefined' && module.exports) {
  module.exports = CookieEditor;
}